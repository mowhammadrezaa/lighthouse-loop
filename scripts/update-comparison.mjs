#!/usr/bin/env node
/**
 * Rebuild COMPARISON.md from all *.report.json files in a directory.
 */
import fs from 'node:fs';
import path from 'node:path';

function arg(name, fallback = null) {
  const i = process.argv.indexOf(name);
  if (i === -1) return fallback;
  return process.argv[i + 1] ?? fallback;
}

function fail(msg) {
  process.stderr.write(`error: ${msg}\n`);
  process.exit(1);
}

function score100(v) {
  if (v == null || Number.isNaN(v)) return '—';
  return String(Math.round(Number(v) * 100));
}

function main() {
  const dir = path.resolve(arg('--dir', './lighthouse-reports'));
  const outName = arg('--out-name', 'COMPARISON.md');
  if (!fs.existsSync(dir)) fail(`Not found: ${dir}`);

  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.report.json'))
    .sort();

  if (!files.length) fail(`No *.report.json in ${dir}`);

  const lines = [
    '# Lighthouse comparison',
    '',
    'Generated by lighthouse-loop. Do not delete older rounds; this file is regenerated.',
    '',
    '| Round | Label | Perf | A11y | BP | SEO | URL |',
    '|---|---|---:|---:|---:|---:|---|',
  ];

  files.forEach((file, idx) => {
    const full = path.join(dir, file);
    const report = JSON.parse(fs.readFileSync(full, 'utf8'));
    const cats = report.categories || {};
    const label = file.replace(/\.report\.json$/, '');
    const url = report.finalDisplayedUrl || report.requestedUrl || '';
    lines.push(
      `| ${idx + 1} | \`${label}\` | ${score100(cats.performance?.score)} | ${score100(cats.accessibility?.score)} | ${score100(cats['best-practices']?.score)} | ${score100(cats.seo?.score)} | ${url} |`,
    );
  });

  lines.push('', '## HTML reports', '');
  for (const file of files) {
    const label = file.replace(/\.report\.json$/, '');
    lines.push(`- [${label}](./${label}.report.html)`);
  }
  lines.push('');

  const out = path.join(dir, outName);
  fs.writeFileSync(out, lines.join('\n'), 'utf8');
  process.stdout.write(`Wrote ${out} (${files.length} rounds)\n`);
}

main();
